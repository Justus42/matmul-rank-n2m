# Test 3: count rank<=1 functionals over GF(7)
p = 7
done = 0
while done < 5:
    A = [[rng.randrange(p) for _ in range(4)] for _ in range(5)]
    B = [[rng.randrange(p) for _ in range(4)] for _ in range(5)]
    if not nonsingular(A, B, p): continue
    assert min_index(A, B, p) == (4, 1)
    n = 0
    for l in itertools.product(range(p), repeat=5):
        # bilinear form (u, x) -> l^T (x1 A + x2 B) u : matrix 4x2 columns l^T A, l^T B
        cA = [sum(l[i] * A[i][j] for i in range(5)) % p for j in range(4)]
        cB = [sum(l[i] * B[i][j] for i in range(5)) % p for j in range(4)]
        if rank_mod([[cA[j], cB[j]] for j in range(4)], p) <= 1: n += 1
    assert n == 1 + (p - 1) * (p + 1), n
    done += 1
print("Test 3: GF(7), 5 nichtsingulaere Buendel: genau 1+(p-1)(p+1) = 49 Funktionale vom Rang <= 1 (p+1 Auswertungspunkte)")
