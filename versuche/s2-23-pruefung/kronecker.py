"""Check of step (A3) in Satz E (S2-16): a 5x4 pencil M(x) = x1*A + x2*B that is injective for
every x != 0 over the algebraic closure is equivalent to a single block L_4^T, i.e. its
polynomial left kernel is generated by one vector of degree 4.  Prime fields GF(p), exact.

Tests:
 1. random pencils over GF(p): nonsingularity over the closure is decided by gcd of the five
    4x4 minors (binary quartics) having no common root (incl. infinity); for each
    nonsingular pencil the minimal left-kernel degree is 4 and the degree-4 kernel is 1-dim.
 2. pencils with a regular block (L_3^T + 1x1 block) are singular somewhere and have minimal
    left-kernel degree < 4 (contrast).
 3. over GF(7): for nonsingular pencils, the functionals l on K^5 with l o M of rank <= 1
    (as 4x2 bilinear form) number exactly 1 + (p-1)(p+1), i.e. p+1 projective points,
    as the L_4^T normal form predicts (l = c * ev_sigma)."""
import random, itertools

def rank_mod(M, p):
    M = [r[:] for r in M]; r = 0
    for c in range(len(M[0]) if M else 0):
        piv = next((i for i in range(r, len(M)) if M[i][c] % p), None)
        if piv is None: continue
        M[r], M[piv] = M[piv], M[r]
        iv = pow(M[r][c], p - 2, p)
        M[r] = [x * iv % p for x in M[r]]
        for i in range(len(M)):
            if i != r and M[i][c] % p:
                f = M[i][c]; M[i] = [(x - f * y) % p for x, y in zip(M[i], M[r])]
        r += 1
    return r

def polymul(a, b, p):
    out = [0] * (len(a) + len(b) - 1)
    for i, x in enumerate(a):
        for j, y in enumerate(b): out[i + j] = (out[i + j] + x * y) % p
    return out

def trim(a):
    while len(a) > 1 and a[-1] == 0: a = a[:-1]
    return a

def polymod(a, b, p):
    a = trim(a[:]); b = trim(b)
    inv = pow(b[-1], p - 2, p)
    while len(a) >= len(b) and any(a):
        f = a[-1] * inv % p; s = len(a) - len(b)
        for i, y in enumerate(b): a[s + i] = (a[s + i] - f * y) % p
        a = trim(a)
    return a

def polygcd(a, b, p):
    a, b = trim(a), trim(b)
    while any(b):
        a, b = b, polymod(a, b, p)
    return a

def det_poly(Mt, p):
    """Mt: 4x4 matrix of polynomials in t (lists). Laplace expansion."""
    n = len(Mt)
    if n == 1: return Mt[0][0]
    res = [0]
    for j in range(n):
        minor = [row[:j] + row[j + 1:] for row in Mt[1:]]
        term = polymul(Mt[0][j], det_poly(minor, p), p)
        if j % 2: term = [(-x) % p for x in term]
        L = max(len(res), len(term))
        res = [((res[i] if i < len(res) else 0) + (term[i] if i < len(term) else 0)) % p for i in range(L)]
    return res

def nonsingular(A, B, p):
    """M(1,t) = A + tB; nonsingular over closure iff gcd of maximal minors is a nonzero constant
    and M(0,1) = B has full column rank (point at infinity)."""
    if rank_mod(B, p) < 4: return False
    g = None
    for drop in range(5):
        rows = [i for i in range(5) if i != drop]
        Mt = [[[A[i][j] % p, B[i][j] % p] for j in range(4)] for i in rows]
        d = trim(det_poly(Mt, p))
        g = d if g is None else polygcd(g, d, p)
    g = trim(g)
    return len(g) == 1 and g[0] != 0

def left_kernel_dim(A, B, d, p):
    """dim of {y(x) = sum_k y_k x1^{d-k} x2^k, y_k in K^5 : y(x)^T M(x) = 0}."""
    # unknowns: (d+1)*5 ; equations: coefficient of x1^{d+1-m} x2^m, m=0..d+1, times 4 columns
    rows = []
    for m in range(d + 2):
        for j in range(4):
            row = [0] * (5 * (d + 1))
            for k in range(d + 1):
                # y_k x1^{d-k}x2^k * (x1 A + x2 B): A-part contributes to m=k, B-part to m=k+1
                for i in range(5):
                    if m == k: row[5 * k + i] = (row[5 * k + i] + A[i][j]) % p
                    if m == k + 1: row[5 * k + i] = (row[5 * k + i] + B[i][j]) % p
            rows.append(row)
    return 5 * (d + 1) - rank_mod(rows, p)

def min_index(A, B, p):
    for d in range(0, 6):
        k = left_kernel_dim(A, B, d, p)
        if k > 0: return d, k
    return None, 0

rng = random.Random(2323)
# Test 1
p = 10007
cnt_ns = 0
for trial in range(300):
    A = [[rng.randrange(p) for _ in range(4)] for _ in range(5)]
    B = [[rng.randrange(p) for _ in range(4)] for _ in range(5)]
    if nonsingular(A, B, p):
        cnt_ns += 1
